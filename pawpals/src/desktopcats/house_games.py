def char_of(a):
    """Which of the five fighters a cat / family member is: the two cats, the first grown-up plays like 爸爸, the
    second like 妈妈 (then it alternates), kids play like 小宝."""
    if a.is_cat:
        return "tabby" if getattr(a.src, "kind", "") == "tabby" else "calico"
    if getattr(a, "role", "adult") == "kid":
        return "kid"
    w = getattr(a, "world", None)
    adults = [p for p in (w.people if w is not None else []) if p.role == "adult"]
    i = adults.index(a) if a in adults else 0
    return "dad" if i % 2 == 0 else "mom"


