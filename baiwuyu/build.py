#!/usr/bin/env python3
"""Regenerate baiwuyu/list.js — the searchable index of all 90 nights across 百物语·壹/贰/叁.
Reads <game>/src/chapters/NN_id.js (id, n, title, sub, origin, legend). Run from anywhere:
    python3 baiwuyu/build.py
"""
import json, os, re, glob

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VOLS = [('nighttales', '壹'), ('guaitan2', '贰'), ('guaitan3', '叁')]

def jstr(src, key):
    m = re.search(r"\b" + key + r":\s*'((?:[^'\\]|\\.)*)'", src)
    return m.group(1).replace("\\'", "'").replace('\\n', ' ') if m else ''

def aka(legend):
    """Original-language name: the first full-width parenthetical of the archive text that is written
    in another script (Latin, kana, hangul, Cyrillic), e.g. 「电梯游戏」（Elevator Game…）."""
    for m in re.finditer(r'（([^（）]{2,80})）', legend[:400]):
        if re.search(r'[A-Za-z\u3040-\u30ff\uac00-\ud7af\u0400-\u04ff]{2}', m.group(1)):
            return m.group(1).split('，')[0]
    return ''

# Hand-set original names where the archive's first parenthetical is something else (a source, a ship…).
AKA = {
    'kuchisake': '口裂け女', 'kunekune': 'くねくね', 'teketeke': 'テケテケ', 'akaheya': '赤い部屋',
    'merry': 'メリーさんの電話', 'kotoribako': 'コトリバコ', 'ushinokubi': '牛の首', 'yotsuya': '東海道四谷怪談',
    'sarayashiki': '番町皿屋敷', 'yukionna': '雪女 · Yuki-onna', 'noppera': 'のっぺらぼう', 'resortbaito': 'リゾートバイト',
    'jangsanbeom': '장산범', 'manananggal': 'Manananggal', 'pocong': 'Pocong', 'toyol': 'Toyol', 'naleba': 'Nale Ba',
    'headless': 'The Headless Horseman', 'celeste': 'Mary Celeste', 'banshee': 'Banshee · bean sídhe',
    'rusalka': 'Русалка', 'dyatlov': 'Перевал Дятлова', 'compana': 'Santa Compaña', 'nokken': 'Näcken',
    'pharaoh': 'Curse of the Pharaohs',
}

# Region groups for the filter chips — matched against the chapter's `origin` line (a night can be in two).
REGIONS = [
    ('日本', r'日本|江户|2ch|小泉八云'),
    ('中国', r'中国|台湾|香港|聊斋|湘西|北京|上海|东北|河南'),
    ('韩国', r'韩国'),
    ('东南亚', r'泰国|菲律宾|印度尼西亚|马来|东南亚'),
    ('南亚 · 中东 · 非洲', r'印度(?!尼)|南非|阿联酋|埃及'),
    ('美洲', r'美国|墨西哥|委内瑞拉|英美|英文网络'),
    ('欧洲', r'英国|英美|苏格兰|爱尔兰|欧洲|德国|歌德|斯拉夫|苏联|布拉格|西班牙|法国|瑞典|阿尔卑斯'),
    ('大洋洲 · 海上', r'澳大利亚|航海|大西洋'),
]

rows = []
for vi, (game, vol) in enumerate(VOLS):
    for f in sorted(glob.glob(os.path.join(ROOT, game, 'src', 'chapters', '*.js'))):
        src = open(f, encoding='utf-8').read()
        head = re.search(r"\bid:\s*'([a-z0-9]+)',\s*n:\s*(\d+),\s*title:", src)
        if not head:
            continue
        hdr = src[head.start():]            # the chapter object: title/sub/origin follow id/n on the same line
        legend = jstr(hdr, 'legend')
        o = jstr(hdr, 'origin')
        rg = [i for i, (_, pat) in enumerate(REGIONS) if re.search(pat, o)]
        if not rg:
            raise SystemExit(f'{game}/{head.group(1)}: no region matches origin {o!r} — extend REGIONS')
        rows.append({
            'v': vi, 'id': head.group(1), 'n': int(head.group(2)),
            't': jstr(hdr, 'title'), 's': jstr(hdr, 'sub'), 'o': o, 'r': rg,
            'a': AKA.get(head.group(1)) or aka(legend), 'k': legend[:400],
        })
rows.sort(key=lambda r: (r['v'], r['n']))
out = os.path.join(ROOT, 'baiwuyu', 'list.js')
with open(out, 'w', encoding='utf-8') as fp:
    fp.write('/* generated by baiwuyu/build.py — do not edit by hand */\n')
    fp.write('window.BWY_VOLS = ' + json.dumps([{'game': g, 'vol': v} for g, v in VOLS], ensure_ascii=False) + ';\n')
    fp.write('window.BWY_REGIONS = ' + json.dumps([r for r, _ in REGIONS], ensure_ascii=False) + ';\n')
    fp.write('window.BWY = ' + json.dumps(rows, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(f'wrote {out}: {len(rows)} nights')
